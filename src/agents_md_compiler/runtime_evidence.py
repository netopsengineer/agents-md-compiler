"""Typed startup evidence and byte-exact, bundle-scoped inspection.

The adapter supports the response-item array emitted by the inspected Codex
producer, not arbitrary JSON nesting. All offsets address UTF-8 bytes in one
original decoded text field. Policy bytes remain internal to this module.
"""

import re
from dataclasses import dataclass
from enum import StrEnum
from itertools import chain
from typing import Literal, cast

from agents_md_compiler.errors import CodexProblem, CodexVerificationError, RenderError
from agents_md_compiler.hashing import sha256_bytes
from agents_md_compiler.models import BundleLock, LockedModule, RenderedBundle
from agents_md_compiler.rendering import build_header, validate_rendered

_PREFIX = b"<!-- agents-md-compiler:"
_CANDIDATE = re.compile(
    rb"^(?:#[^\n]*\n\n)?<!-- agents-md-compiler:generated[^\n]*(?:\n|$)", re.MULTILINE
)
_IDENTITY = re.compile(rb"<!-- bundle-id: ([a-z][a-z0-9-]{0,63}) -->\r?(?:\n|$)")
_HEADER = re.compile(
    rb"# (?:Global )?Agent Instructions\n\n"
    rb"<!-- agents-md-compiler:generated format=([12]) -->\n"
    rb"<!-- bundle-id: ([a-z][a-z0-9-]{0,63}) -->\n"
    rb"<!-- manifest-sha256: ([a-f0-9]{64}) -->\n"
    rb"<!-- lock-sha256: ([a-f0-9]{64}) -->\n"
    rb"<!-- Do not edit this file. Edit canonical sources and regenerate it. -->\n"
)
_BEGIN = re.compile(
    rb"\n<!-- agents-md-compiler:module-begin id=([a-z][a-z0-9-]{0,63}) "
    rb"sha256=([a-f0-9]{64}) bytes=([1-9][0-9]*) -->\n"
)
_BOUNDARY_TOKEN = re.compile(rb"<!-- agents-md-compiler:module-(begin|end)\b[^\n]*")
_END = re.compile(rb"<!-- agents-md-compiler:module-end id=([a-z][a-z0-9-]{0,63}) -->")
_USER_WRAPPER = re.compile(
    r"\A# AGENTS\.md instructions(?: for [^\n]+)?\n\n<INSTRUCTIONS>\n"
)
_USER_END = "\n</INSTRUCTIONS>"
MAX_OVERLAP_DIAGNOSTICS = 1000
"""Bound pairwise diagnostic expansion independently of the input byte limit."""


class DiagnosticCode(StrEnum):
    """Stable runtime-content finding codes, separate from state tokens."""

    UNSUPPORTED_EVIDENCE = "UNSUPPORTED_EVIDENCE"
    SELECTED_BUNDLE_MISSING = "SELECTED_BUNDLE_MISSING"
    DUPLICATE_SELECTED_BUNDLE = "DUPLICATE_SELECTED_BUNDLE"
    AMBIGUOUS_IDENTITY = "AMBIGUOUS_IDENTITY"
    MALFORMED_BOUNDARIES = "MALFORMED_BOUNDARIES"
    MODULE_ORDER = "MODULE_ORDER"
    CONTENT_MISMATCH = "CONTENT_MISMATCH"
    MALFORMED_FOREIGN_BUNDLE = "MALFORMED_FOREIGN_BUNDLE"
    CROSS_BUNDLE_CONTENT_OVERLAP = "CROSS_BUNDLE_CONTENT_OVERLAP"
    MODULE_ID_REUSE = "MODULE_ID_REUSE"
    OVERLAP_SCAN_LIMIT = "OVERLAP_SCAN_LIMIT"


@dataclass(frozen=True, slots=True)
class EvidenceLocation:
    """One half-open UTF-8 byte range in a decoded JSON instruction field."""

    json_path: str
    role: str
    byte_start: int
    byte_end: int


@dataclass(frozen=True, slots=True)
class RuntimeDiagnostic:
    """A policy-free finding with validated identities and evidence locations."""

    code: DiagnosticCode
    severity: Literal["error", "warning", "info"]
    message: str
    bundle_id: str | None = None
    module_id: str | None = None
    sha256: str | None = None
    other_bundle_id: str | None = None
    other_module_id: str | None = None
    other_sha256: str | None = None
    location: EvidenceLocation | None = None
    other_location: EvidenceLocation | None = None


@dataclass(frozen=True, slots=True)
class InstructionEvidence:
    """An admitted field, retaining its original byte coordinates."""

    data: bytes
    location: EvidenceLocation


@dataclass(frozen=True, slots=True)
class _Module:
    identity: LockedModule
    body: bytes
    location: EvidenceLocation


@dataclass(frozen=True, slots=True)
class _Candidate:
    bundle_id: str | None
    data: bytes
    location: EvidenceLocation
    modules: tuple[_Module, ...]
    problem: DiagnosticCode | None
    open_module: bool = False


@dataclass(frozen=True, slots=True)
class ContentInspection:
    """Observed content facts; selected_data is internal and never serialized."""

    selected_bundle_occurrences: int
    modules_verified: int
    content_verified: bool
    overlap_scan_complete: bool
    diagnostics: tuple[RuntimeDiagnostic, ...]
    selected_data: bytes = b""


def extract_instruction_evidence(document: object) -> tuple[InstructionEvidence, ...]:
    """Admit only typed producer instruction fields without normalization.

    Args:
        document: Decoded prompt-input JSON.

    Returns:
        Separate instruction fields in producer order.

    Raises:
        CodexVerificationError: The envelope or a relevant field is unsupported.
    """
    if not isinstance(document, list):
        root_path = "$"
        raise CodexVerificationError(
            CodexProblem.UNSUPPORTED_EVIDENCE, detail=root_path
        )
    fields: list[InstructionEvidence] = []
    for index, raw_item in enumerate(cast("list[object]", document)):
        path = f"$[{index}]"
        if not isinstance(raw_item, dict):
            raise CodexVerificationError(CodexProblem.UNSUPPORTED_EVIDENCE, detail=path)
        item = cast("dict[str, object]", raw_item)
        if not isinstance(item.get("type"), str):
            raise CodexVerificationError(
                CodexProblem.UNSUPPORTED_EVIDENCE, detail=path + ".type"
            )
        if item["type"] != "message":
            continue
        role = item.get("role")
        if not isinstance(role, str):
            raise CodexVerificationError(
                CodexProblem.UNSUPPORTED_EVIDENCE, detail=path + ".role"
            )
        if role not in {"system", "developer", "user"}:
            continue
        content = item.get("content")
        if not isinstance(content, list):
            raise CodexVerificationError(
                CodexProblem.UNSUPPORTED_EVIDENCE, detail=path + ".content"
            )
        for part_index, raw_part in enumerate(cast("list[object]", content)):
            part_path = f"{path}.content[{part_index}]"
            if not isinstance(raw_part, dict):
                raise CodexVerificationError(
                    CodexProblem.UNSUPPORTED_EVIDENCE, detail=part_path
                )
            part = cast("dict[str, object]", raw_part)
            kind = part.get("type")
            if kind in ("input_image", "input_audio", "output_text"):
                continue
            if kind != "input_text" or not isinstance(part.get("text"), str):
                raise CodexVerificationError(
                    CodexProblem.UNSUPPORTED_EVIDENCE, detail=part_path
                )
            text = cast("str", part["text"])
            begin, end = 0, len(text)
            if role == "user":
                if not text.startswith("# AGENTS.md instructions"):
                    continue
                wrapper = _USER_WRAPPER.match(text)
                if wrapper is None or not text.endswith(_USER_END):
                    raise CodexVerificationError(
                        CodexProblem.UNSUPPORTED_EVIDENCE, detail=part_path + ".text"
                    )
                begin, end = wrapper.end(), len(text) - len(_USER_END)
            try:
                encoded = text.encode("utf-8", errors="strict")
                start = len(text[:begin].encode("utf-8"))
                stop = len(text[:end].encode("utf-8"))
            except UnicodeEncodeError as error:
                raise CodexVerificationError(
                    CodexProblem.UNSUPPORTED_EVIDENCE, detail=part_path + ".text"
                ) from error
            fields.append(
                InstructionEvidence(
                    encoded[start:stop],
                    EvidenceLocation(part_path + ".text", role, start, stop),
                )
            )
    return tuple(fields)


def _location(field: InstructionEvidence, start: int, end: int) -> EvidenceLocation:
    return EvidenceLocation(
        field.location.json_path,
        field.location.role,
        field.location.byte_start + start,
        field.location.byte_start + end,
    )


def _has_open_module(region: bytes) -> bool:
    """Track unmatched starts in order, even when a foreign header cannot parse.

    An orphan end cannot pre-close a later start. Malformed starts and mismatched
    ends cannot establish a boundary, so they leave the current nesting open.
    """
    opened: list[bytes | None] = []
    for token in _BOUNDARY_TOKEN.finditer(region):
        if token[1] == b"begin":
            begin = _BEGIN.fullmatch(b"\n" + token[0] + b"\n")
            opened.append(None if begin is None else begin[1])
        else:
            end = _END.fullmatch(token[0])
            if opened and end is not None and opened[-1] == end[1]:
                opened.pop()
    return bool(opened)


def _parse_candidate(
    field: InstructionEvidence, start: int, marker_end: int, stop: int
) -> _Candidate:
    """Parse one token-attributed region; trailing host prose is not bundle data."""
    region = field.data[start:stop]
    identity = _IDENTITY.match(field.data, marker_end)
    bundle_id = None if identity is None else identity[1].decode("ascii")
    modules: list[_Module] = []

    def failed(code: DiagnosticCode, *, open_module: bool = False) -> _Candidate:
        return _Candidate(
            bundle_id,
            region,
            _location(field, start, stop),
            tuple(modules),
            code,
            open_module or _has_open_module(region),
        )

    header = _HEADER.match(region)
    if header is None:
        return failed(DiagnosticCode.MALFORMED_BOUNDARIES)
    version = int(header[1])
    manifest_digest, lock_digest = header[3].decode("ascii"), header[4].decode("ascii")
    offset = header.end()
    seen: set[str] = set()
    while (begin := _BEGIN.match(region, offset)) is not None:
        module_id, digest = begin[1].decode("ascii"), begin[2].decode("ascii")
        # Compare decimal widths before int conversion: hostile integers can exceed
        # Python's conversion limit and cannot fit inside this bounded region.
        if len(begin[3]) > len(str(len(region))):
            return failed(DiagnosticCode.CONTENT_MISMATCH, open_module=True)
        size = int(begin[3])
        body_start, body_end = begin.end(), begin.end() + size
        body = region[body_start:body_end]
        end = f"<!-- agents-md-compiler:module-end id={module_id} -->\n".encode("ascii")
        if len(body) != size or not region.startswith(end, body_end):
            return failed(DiagnosticCode.MALFORMED_BOUNDARIES, open_module=True)
        if module_id in seen or _PREFIX in body:
            return failed(DiagnosticCode.MALFORMED_BOUNDARIES)
        if (
            sha256_bytes(body) != digest
            or not body.endswith(b"\n")
            or body.endswith(b"\n\n")
            or body.startswith(b"\xef\xbb\xbf")
            or b"\r" in body
            or b"\x00" in body
        ):
            return failed(DiagnosticCode.CONTENT_MISMATCH)
        seen.add(module_id)
        modules.append(
            _Module(
                LockedModule(module_id, "", digest, size),
                body,
                _location(field, start + body_start, start + body_end),
            )
        )
        offset = body_end + len(end)
    if not modules or _PREFIX in region[offset:]:
        return failed(DiagnosticCode.MALFORMED_BOUNDARIES)
    data = region[:offset]
    lock = BundleLock(
        header[2].decode("ascii"),
        version,
        manifest_digest,
        tuple(module.identity for module in modules),
    )
    try:
        validate_rendered(data, lock, lock_digest)
    except RenderError:
        return failed(DiagnosticCode.MALFORMED_BOUNDARIES)
    return _Candidate(
        bundle_id, data, _location(field, start, start + offset), tuple(modules), None
    )


def _candidates(fields: tuple[InstructionEvidence, ...]) -> tuple[_Candidate, ...]:
    found: list[_Candidate] = []
    for field in fields:
        matches = list(_CANDIDATE.finditer(field.data))
        prefix_end = matches[0].start() if matches else len(field.data)
        if _PREFIX in field.data[:prefix_end]:
            found.append(
                _Candidate(
                    None,
                    b"",
                    _location(field, 0, prefix_end),
                    (),
                    DiagnosticCode.MALFORMED_BOUNDARIES,
                )
            )
        for index, match in enumerate(matches):
            stop = (
                matches[index + 1].start()
                if index + 1 < len(matches)
                else len(field.data)
            )
            found.append(_parse_candidate(field, match.start(), match.end(), stop))
    return tuple(found)


def _overlaps(
    candidates: tuple[_Candidate, ...],
) -> tuple[list[RuntimeDiagnostic], bool]:
    findings: list[RuntimeDiagnostic] = []
    by_digest: dict[str, dict[str | None, list[tuple[_Candidate, _Module]]]] = {}
    by_id: dict[str, dict[str | None, list[tuple[_Candidate, _Module]]]] = {}
    for candidate in candidates:
        if candidate.problem is not None:
            continue
        for module in candidate.modules:
            digest, module_id = module.identity.sha256, module.identity.id
            # Group by bundle identity before comparing: repeated copies of one
            # identity cannot cause quadratic work with no reportable findings.
            same_digest = (
                (other, previous, DiagnosticCode.CROSS_BUNDLE_CONTENT_OVERLAP)
                for identity, entries in by_digest.get(digest, {}).items()
                if identity != candidate.bundle_id
                for other, previous in entries
                if previous.body == module.body
            )
            same_id = (
                (other, previous, DiagnosticCode.MODULE_ID_REUSE)
                for identity, entries in by_id.get(module_id, {}).items()
                if identity != candidate.bundle_id
                for other, previous in entries
                if previous.body != module.body
            )
            for other, previous, code in chain(same_digest, same_id):
                if len(findings) == MAX_OVERLAP_DIAGNOSTICS:
                    findings.append(
                        RuntimeDiagnostic(
                            DiagnosticCode.OVERLAP_SCAN_LIMIT,
                            "warning",
                            "overlap diagnostic limit reached; inspection is incomplete",
                        )
                    )
                    return findings, False
                findings.append(
                    RuntimeDiagnostic(
                        code,
                        "warning"
                        if code is DiagnosticCode.CROSS_BUNDLE_CONTENT_OVERLAP
                        else "info",
                        "identical complete module bodies"
                        if code is DiagnosticCode.CROSS_BUNDLE_CONTENT_OVERLAP
                        else "module identifier reused with different content",
                        other.bundle_id,
                        previous.identity.id,
                        previous.identity.sha256,
                        candidate.bundle_id,
                        module_id,
                        digest,
                        previous.location,
                        module.location,
                    )
                )
            by_digest.setdefault(digest, {}).setdefault(candidate.bundle_id, []).append(
                (candidate, module)
            )
            by_id.setdefault(module_id, {}).setdefault(candidate.bundle_id, []).append(
                (candidate, module)
            )
    return findings, True


def inspect_content(
    rendered: RenderedBundle, fields: tuple[InstructionEvidence, ...]
) -> ContentInspection:
    """Verify one complete selected occurrence and inspect distinct identities.

    Args:
        rendered: Compiled selection, with validated format-2 bytes.
        fields: Separate admitted instruction fields.

    Returns:
        Content facts and ordered, policy-free findings.
    """
    candidates = _candidates(fields)
    selected = [item for item in candidates if item.bundle_id == rendered.bundle_id]
    foreign_bad = tuple(
        item
        for item in candidates
        if item.bundle_id != rendered.bundle_id and item.problem is not None
    )
    diagnostics = [
        RuntimeDiagnostic(
            DiagnosticCode.MALFORMED_FOREIGN_BUNDLE,
            "warning",
            "foreign candidate is not structurally complete; overlap inspection is incomplete",
            bundle_id=item.bundle_id,
            location=item.location,
        )
        for item in foreign_bad
    ]
    code: DiagnosticCode | None = None
    verified = 0
    data = b""
    if not selected:
        code = DiagnosticCode.SELECTED_BUNDLE_MISSING
    elif len(selected) > 1:
        code = (
            DiagnosticCode.DUPLICATE_SELECTED_BUNDLE
            if all(
                item.problem is None and item.data == rendered.data for item in selected
            )
            else DiagnosticCode.AMBIGUOUS_IDENTITY
        )
    else:
        candidate = selected[0]
        data = candidate.data
        expected_offset = len(
            build_header(
                bundle_id=rendered.bundle_id,
                manifest_sha256=rendered.manifest_sha256,
                lock_sha256=rendered.lock_sha256,
            )
        )
        # Truncation is intentional: count only pairs that actually exist.
        for observed, expected in zip(
            candidate.modules, rendered.modules, strict=False
        ):
            # Expected body offsets derive only from compiler-validated metadata.
            expected_offset = rendered.data.index(b"\n", expected_offset + 1) + 1
            expected_body = rendered.data[
                expected_offset : expected_offset + expected.size_bytes
            ]
            expected_offset += expected.size_bytes
            expected_offset = rendered.data.index(b"\n", expected_offset) + 1
            if (
                observed.identity.id == expected.id
                and observed.body == expected_body
                and observed.identity.sha256 == expected.sha256
            ):
                verified += 1
        if candidate.problem is not None:
            code = candidate.problem
        elif tuple(module.identity.id for module in candidate.modules) != tuple(
            module.id for module in rendered.modules
        ):
            code = DiagnosticCode.MODULE_ORDER
        elif data != rendered.data:
            code = DiagnosticCode.CONTENT_MISMATCH
        if any(
            item.bundle_id is None
            or (
                item.open_module
                and item.location.json_path == candidate.location.json_path
                and item.location.byte_start < candidate.location.byte_start
            )
            for item in foreign_bad
        ):
            code = DiagnosticCode.AMBIGUOUS_IDENTITY
    if code is not None:
        diagnostics.insert(
            0,
            RuntimeDiagnostic(
                code,
                "error",
                CodexProblem[code.name].value,
                bundle_id=rendered.bundle_id,
                location=selected[0].location if selected else None,
                other_location=selected[1].location if len(selected) > 1 else None,
            ),
        )
    overlaps, complete = _overlaps(candidates)
    diagnostics.extend(overlaps)
    return ContentInspection(
        len(selected),
        verified,
        code is None,
        complete and not foreign_bad,
        tuple(diagnostics),
        data,
    )
