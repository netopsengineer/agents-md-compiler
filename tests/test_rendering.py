ABSENT_TARGET = Path("/nonexistent/agents-md-compiler-test-target/AGENTS.md")


def compiled_for(manifest_path: Path) -> CompiledBundle:
    """Compile a bundle from a manifest on disk.

    Args:
        manifest_path: Manifest to read.

    Returns:
        The compiled bundle.
    """
    return compile_bundle(load_manifest(manifest_path), target=ABSENT_TARGET)


def rendered_for(manifest_path: Path) -> RenderedBundle:
    """Render a bundle from a manifest on disk.

    Args:
        manifest_path: Manifest to read.

    Returns:
        The rendered bundle.
    """
    manifest = load_manifest(manifest_path)
    snapshots = read_sources(manifest.modules)
    lock = build_lock(manifest, snapshots)
    return rendering.render_bundle(
        bundle_id=manifest.bundle_id,
        manifest_sha256=manifest.sha256,
        lock_sha256=lock_digest(lock),
        snapshots=snapshots,
    )


def test_rendered_bytes_match_the_hand_authored_golden() -> None:
    manifest = load_manifest(MANIFEST_FIXTURES / "minimal.toml")
    snapshots = read_sources(manifest.modules)
    lock = build_lock(manifest, snapshots)
    digest = sha256_bytes(serialize_lock(lock))
    rendered = rendering.render_bundle(
        bundle_id=manifest.bundle_id,
        manifest_sha256=manifest.sha256,
        lock_sha256=digest,
        snapshots=snapshots,
    )
    expected = (
        (GOLDEN / "minimal.render.md.tmpl")
        .read_text(encoding="utf-8")
        .replace("__LOCK_SHA256__", digest)
        .encode("utf-8")
    )
    assert rendered.data == expected


def test_the_header_has_exactly_seven_lines(bundle: Bundle) -> None:
    rendered = rendered_for(bundle.manifest)
    lines = rendered.data.split(b"\n")
    assert lines[0] == BUNDLE_TITLE.encode("ascii")
    assert lines[1] == b""
    assert (
        lines[2]
        == f"<!-- agents-md-compiler:generated format={RENDER_FORMAT_VERSION} -->".encode()
    )
    assert lines[3].startswith(b"<!-- bundle-id: ")
    assert lines[4].startswith(b"<!-- manifest-sha256: ")
    assert lines[5].startswith(b"<!-- lock-sha256: ")
    assert lines[6].startswith(b"<!-- Do not edit this file.")
    assert lines[7] == b""


