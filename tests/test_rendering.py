def test_self_validation_accepts_freshly_rendered_bytes(
    three_module_bundle: Bundle,
) -> None:
    manifest = load_manifest(three_module_bundle.manifest)
    snapshots = read_sources(manifest.modules)
    lock = build_lock(manifest, snapshots)
    digest = lock_digest(lock)
    rendered = rendering.render_bundle(
        bundle_id=manifest.bundle_id,
        manifest_sha256=manifest.sha256,
        lock_sha256=digest,
        snapshots=snapshots,
    )
    rendering.validate_rendered(rendered.data, lock, digest)


def validated_parts(manifest_path: Path) -> tuple[bytes, BundleLock, str]:
    """Produce rendered bytes plus the lock and digest they must satisfy.

    Args:
        manifest_path: Manifest to read.

    Returns:
        The rendered bytes, the lock, and the lock digest.
    """
    manifest = load_manifest(manifest_path)
    snapshots = read_sources(manifest.modules)
    lock = build_lock(manifest, snapshots)
    digest = lock_digest(lock)
    rendered = rendering.render_bundle(
        bundle_id=manifest.bundle_id,
        manifest_sha256=manifest.sha256,
        lock_sha256=digest,
        snapshots=snapshots,
    )
    return rendered.data, lock, digest


def test_self_validation_rejects_a_changed_header(bundle: Bundle) -> None:
    data, lock, digest = validated_parts(bundle.manifest)
    damaged = data.replace(BUNDLE_TITLE.encode("ascii"), b"# Something Else", 1)
    with pytest.raises(RenderError) as raised:
        rendering.validate_rendered(damaged, lock, digest)
    assert raised.value.problem is RenderProblem.HEADER_MISMATCH


def test_self_validation_rejects_a_wrong_lock_digest(bundle: Bundle) -> None:
    data, lock, _ = validated_parts(bundle.manifest)
    with pytest.raises(RenderError) as raised:
        rendering.validate_rendered(data, lock, "c" * 64)
    assert raised.value.problem is RenderProblem.HEADER_MISMATCH


