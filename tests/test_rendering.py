def test_exact_source_bytes_are_preserved(bundle: Bundle) -> None:
    data = rendered_for(bundle.manifest).data
    for source in bundle.modules.values():
        assert source.read_bytes() in data


def test_each_module_is_wrapped_by_its_own_markers(three_module_bundle: Bundle) -> None:
    rendered = rendered_for(three_module_bundle.manifest)
    text = rendered.data.decode("utf-8")
    for module in rendered.modules:
        assert rendering.begin_marker(module) in text
        assert rendering.end_marker(module) in text


def test_first_middle_and_last_modules_are_all_present_in_order(
    three_module_bundle: Bundle,
) -> None:
    rendered = rendered_for(three_module_bundle.manifest)
    text = rendered.data.decode("utf-8")
    positions = [
        text.index(f"module-begin id={module.id} ") for module in rendered.modules
    ]
    assert [module.id for module in rendered.modules] == ["core", "python", "extras"]
    assert positions == sorted(positions)
    assert "# Core Policy" in text
    assert "# Python Policy" in text
    assert "# Extra Policy" in text


