def test_reordering_the_manifest_reorders_the_output(tmp_path: Path) -> None:
    forward = make_bundle(
        tmp_path / "a", module_texts=(("core", CORE_TEXT), ("python", PYTHON_TEXT))
    )
    reverse = make_bundle(
        tmp_path / "b", module_texts=(("python", PYTHON_TEXT), ("core", CORE_TEXT))
    )
    assert [m.id for m in rendered_for(forward.manifest).modules] == ["core", "python"]
    assert [m.id for m in rendered_for(reverse.manifest).modules] == ["python", "core"]


