def snapshot(
    *,
    module_id: str = "core",
    data: bytes = b"# Core\n",
    digest: str | None = None,
    size: int | None = None,
) -> SourceSnapshot:
    """Build a snapshot, optionally with a deliberately wrong digest or size.

    Args:
        module_id: Module identifier.
        data: Content bytes.
        digest: Override digest.
        size: Override declared size.

    Returns:
        The snapshot.
    """
    return SourceSnapshot(
        id=module_id,
        lexical_source="core.md",
        resolved_source=Path("/example/core.md"),
        data=data,
        sha256=sha256_bytes(data) if digest is None else digest,
        size_bytes=len(data) if size is None else size,
    )


