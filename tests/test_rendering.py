def test_compiled_bundle_self_validates(bundle: Bundle) -> None:
    compiled = compiled_for(bundle.manifest)
    assert isinstance(compiled.rendered, RenderedBundle)
    assert compiled.rendered.sha256 == sha256_bytes(compiled.rendered.data)
    assert compiled.rendered.size_bytes == len(compiled.rendered.data)
    assert compiled.lock_sha256 == sha256_bytes(compiled.lock_bytes)
